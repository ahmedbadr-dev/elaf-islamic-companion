const STORAGE_KEY = 'elaf-prayer-verse'

export function verseIndexForPrayer(date: Date, nextPrayerIndex: number): number {
  const start = new Date(date.getFullYear(), 0, 0)
  const dayOfYear = Math.floor((date.getTime() - start.getTime()) / 86400000)
  const n = PRAYER_VERSES.length
  return (dayOfYear * 7 + nextPrayerIndex * 3) % n
}

export function getVerseForPrayer(date: Date, nextPrayerIndex: number): DailyVerse {
  return PRAYER_VERSES[verseIndexForPrayer(date, nextPrayerIndex)]
}

export function loadVerseSession(): { periodKey: string; verseIndex: number } | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    return raw ? JSON.parse(raw) : null
  } catch {
    return null
  }
}

export function saveVerseSession(periodKey: string, verseIndex: number) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ periodKey, verseIndex }))
  } catch {
    /* ignore */
  }
}

export function prayerPeriodKey(date: Date, nextPrayerIndex: number): string {
  const y = date.getFullYear()
  const m = String(date.getMonth() + 1).padStart(2, '0')
  const d = String(date.getDate()).padStart(2, '0')
  return `${y}-${m}-${d}#${nextPrayerIndex}`
}
